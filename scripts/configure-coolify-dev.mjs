import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const POSTGRES_UUID = "ea800nple5jhvjimjspbdzse";
const REDIS_UUID = "7v7qlkrhj8f35tyd98dt6p3f";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryDirectory = resolve(scriptDirectory, "..");
const outputPath = resolve(repositoryDirectory, ".env");
const platformEnvironmentPath = process.env.NOYRA_PLATFORM_ENV_FILE
  ? resolve(process.env.NOYRA_PLATFORM_ENV_FILE)
  : resolve(repositoryDirectory, "..", "noyra-platform", ".env");

function parseEnvironment(content) {
  const values = new Map();

  for (const line of content.split(/\r?\n/)) {
    const match = line.match(/^\s*([^#][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/);
    if (!match) continue;

    let value = match[2].trim();
    if (
      value.length >= 2 &&
      ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'")))
    ) {
      value = value.slice(1, -1);
    }
    values.set(match[1], value);
  }

  return values;
}

function required(values, key, source) {
  const value = values.get(key)?.trim();
  if (!value) throw new Error(`${key} is missing from ${source}.`);
  return value;
}

function secret(existing, key) {
  return existing.get(key)?.trim() || randomBytes(32).toString("base64url");
}

function quote(value) {
  return JSON.stringify(value);
}

async function coolifyDatabase(baseUrl, apiKey, uuid) {
  const response = await fetch(`${baseUrl}/databases/${uuid}`, {
    headers: {
      Accept: "application/json",
      Authorization: `Bearer ${apiKey}`,
    },
    signal: AbortSignal.timeout(20_000),
  });

  if (!response.ok) {
    throw new Error(
      `Coolify database lookup failed with HTTP ${response.status}.`,
    );
  }

  const database = await response.json();
  if (!database.status?.startsWith("running")) {
    throw new Error(`${database.name ?? uuid} is not running.`);
  }
  if (!database.external_db_url) {
    throw new Error(`${database.name ?? uuid} has no external connection URL.`);
  }

  return database.external_db_url;
}

if (!existsSync(platformEnvironmentPath)) {
  throw new Error(`Noyra platform environment not found at ${platformEnvironmentPath}.`);
}

const controlPlaneEnvironment = parseEnvironment(
  readFileSync(platformEnvironmentPath, "utf8"),
);
const existingEnvironment = existsSync(outputPath)
  ? parseEnvironment(readFileSync(outputPath, "utf8"))
  : new Map();

const configuredApiUrl = required(
  controlPlaneEnvironment,
  "COOLIFY_API_URL",
  platformEnvironmentPath,
).replace(/\/$/, "");
const apiUrl = `${configuredApiUrl.replace(/\/api\/v1$/, "")}/api/v1`;
const apiKey = required(
  controlPlaneEnvironment,
  "COOLIFY_API_KEY",
  platformEnvironmentPath,
);

const [databaseUrl, redisUrl] = await Promise.all([
  coolifyDatabase(apiUrl, apiKey, POSTGRES_UUID),
  coolifyDatabase(apiUrl, apiKey, REDIS_UUID),
]);

const content = `# Generated by pnpm setup:coolify-dev. This file is gitignored.
# Postgres and Redis are isolated development resources hosted in Coolify.
DATABASE_URL=${quote(databaseUrl)}
REDIS_URL=${quote(redisUrl)}
REDIS_KEY_PREFIX="usesend-dev:"

NEXTAUTH_URL="http://localhost:3000"
NEXTAUTH_SECRET=${quote(secret(existingEnvironment, "NEXTAUTH_SECRET"))}
NOYRA_API_KEY=${quote(secret(existingEnvironment, "NOYRA_API_KEY"))}

# Local development credentials. Configure the SES emulator before testing delivery.
AWS_DEFAULT_REGION="us-east-1"
AWS_ACCESS_KEY_ID="local-development"
AWS_SECRET_ACCESS_KEY="local-development"
FROM_EMAIL="hello@usesend.local"

API_RATE_LIMIT=20
AUTH_EMAIL_RATE_LIMIT=20
NEXT_PUBLIC_IS_CLOUD=false
`;

writeFileSync(outputPath, content, { encoding: "utf8", mode: 0o600 });
console.log("Configured .env with the healthy Coolify development databases.");
